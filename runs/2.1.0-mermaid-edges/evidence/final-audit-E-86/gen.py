def blocks(path):
    L=open(path).read().split('\n'); res=[]; i=0
    while i<len(L):
        if L[i].startswith('$ '):
            cmd=[L[i][2:]]; i+=1
            if '<<SCRIPT' in cmd[0]:
                while L[i-1]!=')"': cmd.append(L[i]); i+=1
            body=[]
            while i<len(L) and not L[i].startswith('$ '): body.append(L[i]); i+=1
            ex=None
            while body and body[-1]=='': body.pop()
            if body and re.match(r'^exit( code)?: \d+$',body[-1]): ex=int(body.pop().split()[-1])
            res.append(('\n'.join(cmd),'\n'.join(body),ex))
        else: i+=1
    return res
