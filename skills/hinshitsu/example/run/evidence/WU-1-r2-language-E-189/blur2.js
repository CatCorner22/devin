const { chromium } = require('/home/ubuntu/pwtools/node_modules/playwright');
const { execSync } = require('child_process');
const url = 'file:///home/ubuntu/repos/devin/skills/hinshitsu/example/index.html';
(async () => {
  const browser = await chromium.launch({ executablePath: '/home/ubuntu/.local/bin/google-chrome', headless: false });
  const ctx = await browser.newContext();
  const page = await ctx.newPage(); await page.goto(url);
  const cdp = await ctx.newCDPSession(page);
  await cdp.send('Emulation.setFocusEmulationEnabled', { enabled: false });
  const st = () => page.evaluate(() => ({ bill: document.getElementById('bill').value, be: document.getElementById('bill-error').textContent, active: document.activeElement.id, hasFocus: document.hasFocus(), ev: window.__ev, lines: document.querySelectorAll('#result p').length }));
  const hook = () => page.evaluate(() => { window.__ev = []; ['blur','focus'].forEach(t => { window.addEventListener(t, () => window.__ev.push('window ' + t)); document.getElementById('bill').addEventListener(t, () => window.__ev.push('bill ' + t)); }); });
  const page2 = await ctx.newPage(); await page2.goto('about:blank');
  const cdp2 = await ctx.newCDPSession(page2);
  await page.bringToFront(); await page.waitForTimeout(500);
  await hook(); await page.click('#bill'); await page.waitForTimeout(300);
  console.log('1. bill clicked, nothing typed:', JSON.stringify(await st()));
  await page2.bringToFront(); await page.waitForTimeout(1000);
  console.log('1. after another tab of the same window came to the front:', JSON.stringify(await st()));
  await page.bringToFront(); await page.waitForTimeout(500);
  await page.reload(); await hook();
  await page.click('#tip'); await page.keyboard.type('18'); await page.click('#people'); await page.keyboard.type('4'); await page.click('#bill'); await page.keyboard.type('12.');
  await page.waitForTimeout(300);
  console.log('2. 12. typed in bill:', JSON.stringify(await st()));
  await page2.bringToFront(); await page.waitForTimeout(1000);
  console.log('2. after another tab of the same window came to the front:', JSON.stringify(await st()));
  await page.bringToFront(); await page.waitForTimeout(800);
  console.log('2. after the person came back to the tab:', JSON.stringify(await st()));
  await page.click('#tip'); await page.waitForTimeout(300);
  console.log('2. after the person then clicked the tip field:', JSON.stringify(await st()));
  await browser.close();
})().catch(e => { console.error('SCRIPT ERROR', e); process.exit(1); });
